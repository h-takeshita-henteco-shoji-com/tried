def segs(path, start, end, n):
    """録画を n 本に切って並べる。同じ clip をくり返すと、行ごとに頭から流れ直すため。"""
    step = (end - start) / n
    return [clip(path, start + i * step, start + (i + 1) * step) for i in range(n)]


